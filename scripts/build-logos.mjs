// Copies the reviewed logos into public/brands (SVG as is, PNG as WebP) and writes lib/brand-logos.ts.
// node scripts/build-logos.mjs
import fs from 'node:fs';
import path from 'node:path';
import sharp from 'sharp';

const src = '.image-work/logos';
const dst = 'public/brands';
fs.mkdirSync(dst, { recursive: true });

const BRANDS = [
  ['Kalkhoff', 'kalkhoff', '/marken/kalkhoff'],
  ['Haibike', 'haibike', '/marken/haibike'],
  ['Riese & Müller', 'riese-und-mueller', '/marken/riese-und-mueller'],
  ['Cube', 'cube', '/marken/cube'],
  ['Specialized', 'specialized', '/marken/specialized'],
  ['Gazelle', 'gazelle', '/marken/gazelle'],
  ['Canyon', 'canyon', '/marken/canyon'],
  ['Tenways', 'tenways', '/marken/tenways'],
  ['Focus', 'focus', '/marken/focus'],
  ['Winora', 'winora', '/marken/winora'],
  ['Ghost', 'ghost', '/marken/ghost'],
  ['KTM', 'ktm', '/marken/ktm'],
  ['Trek', 'trek', '/marken/trek'],
  ['Giant', 'giant', '/marken/giant'],
  ['Brompton', 'brompton', '/marken/brompton'],
];
// svgs drawn small inside a large canvas: rasterise and trim so the logo fills its tile
const TRIM_SVG = new Set(['kalkhoff']);
const SKIP = new Set(JSON.parse(process.env.SKIP_LOGOS || '[]'));
const out = [];
for (const [name, slug, hub] of BRANDS) {
  if (SKIP.has(slug)) continue;
  const file = fs.readdirSync(src).find((f) => f.startsWith(slug + '.'));
  if (!file) { console.log('no logo for', slug); continue; }
  const ext = path.extname(file).toLowerCase();
  let name2;
  if (ext === '.svg' && !TRIM_SVG.has(slug)) {
    fs.copyFileSync(path.join(src, file), path.join(dst, `${slug}.svg`));
    name2 = `${slug}.svg`;
  } else {
    await sharp(path.join(src, file), { density: 900 }).flatten({ background: '#ffffff' }).trim({ threshold: 12 }).resize({ width: 420, withoutEnlargement: true }).webp({ quality: 88 }).toFile(path.join(dst, `${slug}.webp`));
    name2 = `${slug}.webp`;
  }
  out.push({ name, slug, hub, logo: `/brands/${name2}` });
}
const header = `// Brand logos shown to identify the brands the shop sells (dealer use). Logos are trademarks of their owners.\n// Generated by scripts/build-logos.mjs from reviewed files; sources: Wikimedia Commons and the brands' own sites.\n`;
fs.writeFileSync('lib/brand-logos.ts', `${header}\nexport interface BrandLogo { name: string; slug: string; hub: string; logo: string }\n\nexport const BRAND_LOGOS: BrandLogo[] = ${JSON.stringify(out, null, 2)};\n`);
console.log('logos written:', out.length);
